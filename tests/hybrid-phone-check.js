async (page) => {
  const checks = [];
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const fixture = (body) => page.request.post('http://127.0.0.1:8756/__fixture', { data: body });
  const selected = async (which, value) => {
    await page.waitForFunction(({ which, value }) => document.querySelectorAll('select[aria-label="TV platform"]')[which]?.value === value, { which, value });
  };
  await fixture({ active: 'android', clear_events: true });
  await page.setViewportSize({ width: 393, height: 852 });
  await page.goto('http://127.0.0.1:8756/');
  const selectors = page.getByRole('combobox', { name: 'TV platform' });
  await selectors.first().waitFor();
  await selectors.first().selectOption('apple');
  await page.waitForFunction(() => !document.querySelector('select[aria-label="TV platform"]').disabled);
  await selected(0, 'apple');
  checks.push('Apple TV selection confirmed');
  await page.getByRole('button', { name: 'Home', exact: true }).click();
  await page.getByRole('button', { name: 'Open YouTube on the TV', exact: true }).click();
  await page.screenshot({ path: 'output/apple-tv/phone-platform-apple.png' });
  await page.getByRole('button', { name: 'Watch', exact: true }).click();
  await page.waitForFunction(() => Math.abs(document.querySelector('.pager').scrollLeft - document.querySelector('.pager').clientWidth) < 2);
  const search = page.getByRole('searchbox', { name: 'Search films and TV shows' });
  await search.fill('Bluey');
  await page.locator('.stremio-title').first().waitFor();
  await selected(1, 'apple');
  await page.screenshot({ path: 'output/apple-tv/phone-watch-apple.png' });
  await selectors.last().selectOption('android');
  await page.waitForFunction(() => !document.querySelectorAll('select[aria-label="TV platform"]')[1].disabled);
  await selected(1, 'android');
  if (await search.inputValue() !== 'Bluey') throw new Error('Changing platform lost the search query');
  checks.push('Watch selector follows the same input without losing search');
  await page.locator('.stremio-title').first().click();
  await page.locator('.watch').evaluate((element) => { element.scrollTop = element.scrollHeight; });
  await page.getByRole('button', { name: 'Open title in Stremio on TV', exact: true }).click();
  await page.getByRole('button', { name: 'Home', exact: true }).waitFor({ state: 'visible' });
  await fixture({ active: 'apple' });
  await selected(0, 'apple');
  checks.push('External input change updates the selector');
  await page.getByRole('button', { name: 'Home', exact: true }).click();
  await fixture({ active: 'android', fail_switch: true });
  await selected(0, 'android');
  await selectors.first().selectOption('apple');
  await page.waitForFunction(() => !document.querySelector('select[aria-label="TV platform"]').disabled);
  await selected(0, 'android');
  await page.getByText('Apple TV is unavailable. The current input has been kept.', { exact: true }).waitFor();
  checks.push('Failed switch preserves the observed platform and displays the error');
  await fixture({ active: 'other' });
  await page.waitForFunction(() => document.querySelector('select[aria-label="TV platform"]').selectedOptions[0].textContent === 'Other input');
  await selectors.first().selectOption('android');
  await selected(0, 'android');
  checks.push('Unknown input can be recovered with an explicit choice');
  await page.getByRole('button', { name: 'More controls', exact: true }).click();
  await page.getByRole('button', { name: 'Connect Apple TV', exact: true }).click();
  await page.getByText('123 456', { exact: true }).waitFor();
  checks.push('One-off Apple TV connection code appears without changing input');
  const events = (await (await page.request.get('http://127.0.0.1:8756/__fixture')).json()).events;
  const home = events.filter((event) => event.path === '/api/key' && event.body.key === 'home');
  if (home.length !== 2 || home.some((event) => event.platform !== 'apple')) throw new Error('Home dispatch did not follow Apple TV');
  if (!events.some((event) => event.path === '/api/launch' && event.body.app === 'youtube' && event.platform === 'apple')) throw new Error('YouTube did not follow Apple TV');
  if (!events.some((event) => event.path === '/api/stremio/open' && event.platform === 'android')) throw new Error('Search did not follow the changed input');
  checks.push('Home, YouTube and title APIs dispatch on the current platform');
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow || errors.length) throw new Error(JSON.stringify({ overflow, errors }));
  checks.push('393px layout has no page overflow or JavaScript exception');
  return { checks, events, errors };
}
