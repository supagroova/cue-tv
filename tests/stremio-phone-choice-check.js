async (page) => {
  const checks = [], errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const fixture = (data) => page.request.post('http://127.0.0.1:8756/__fixture', { data });
  const state = async () => (await (await page.request.get('http://127.0.0.1:8756/__fixture')).json());
  await fixture({ active: 'android', clear_events: true, stremio_detail_error: false, stremio_sources_error: false, stremio_sources_empty: false, stremio_play_error: false, stremio_provider_failed: false });
  await page.setViewportSize({ width: 393, height: 852 });
  await page.goto('http://127.0.0.1:8756/');
  await page.getByRole('button', { name: 'Watch', exact: true }).click();
  const search = page.getByRole('searchbox', { name: 'Search films and TV shows' });
  await search.fill('Bluey');
  await page.locator('.stremio-title').first().click();
  const seasons = page.getByRole('combobox', { name: 'Season', exact: true });
  await seasons.selectOption('2');
  await page.getByRole('button', { name: 'Episode 1: Season two opener', exact: true }).waitFor();
  if (!await page.getByRole('button', { name: 'Episode 2: Not released yet', exact: true }).isDisabled()) throw Error('Future episode was selectable');
  await page.screenshot({ path: 'output/apple-tv/phone-stremio-episodes.png' });
  await page.getByRole('button', { name: 'Episode 1: Season two opener', exact: true }).click();
  await page.getByRole('heading', { name: 'Choose a source', exact: true }).waitFor();
  const filter = page.getByRole('searchbox', { name: 'Filter sources', exact: true });
  await filter.fill('4K');
  if (await page.locator('.stremio-source').count() !== 2) throw Error('Source quality filter failed');
  if ((await state()).events.some((event) => event.path === '/api/stremio/play' || event.path === '/api/stremio/open')) throw Error('Browsing started TV playback');
  checks.push('Show, season and episode browsing leaves TV playback alone; future episodes are disabled');
  await page.screenshot({ path: 'output/apple-tv/phone-stremio-sources.png' });
  await page.getByRole('combobox', { name: 'TV platform' }).last().selectOption('apple');
  await page.waitForFunction(() => document.querySelectorAll('select[aria-label="TV platform"]')[1]?.value === 'apple' && !document.querySelectorAll('select[aria-label="TV platform"]')[1]?.disabled);
  await fixture({ stremio_play_error: true });
  const chosen = page.getByRole('button', { name: 'Play 4K HDR from Fixture provider', exact: true });
  await chosen.click();
  await page.getByText('Stremio could not open that source.', { exact: true }).waitFor();
  await chosen.waitFor({ state: 'visible' });
  await fixture({ stremio_play_error: false });
  await chosen.click();
  await page.getByRole('button', { name: 'Home', exact: true }).waitFor({ state: 'visible' });
  const plays = (await state()).events.filter((event) => event.path === '/api/stremio/play');
  if (plays.length !== 2 || plays[1].platform !== 'apple' || plays[1].choice.quality !== '4K HDR' || !plays[1].choice.video.endsWith(':2:1')) throw Error('The exact episode, source or active platform changed');
  if (Object.keys(plays[1].body).join() !== 'id' || !/^[a-f0-9]{32}$/.test(plays[1].body.id)) throw Error('Phone playback sent more than the opaque choice');
  checks.push('Exact season 2 episode 1 and 4K source follows Apple TV selection; failed playback keeps the chooser open for retry');
  await page.getByRole('button', { name: 'Watch', exact: true }).click();
  await page.getByRole('button', { name: '‹ Episodes', exact: true }).click();
  await page.getByRole('button', { name: '‹ Watch Now', exact: true }).click();
  if (await search.inputValue() !== 'Bluey') throw Error('Search was lost after playback');
  await page.locator('.stremio-title').first().click();
  await seasons.selectOption('0');
  await page.getByRole('button', { name: 'Episode 1: Special episode', exact: true }).click();
  await filter.waitFor();
  await page.getByRole('button', { name: '‹ Episodes', exact: true }).click();
  if (await seasons.inputValue() !== '0') throw Error('Back lost the selected season');
  await page.getByRole('button', { name: '‹ Watch Now', exact: true }).click();
  if (await search.inputValue() !== 'Bluey') throw Error('Back lost the search');
  checks.push('Specials, back navigation and search restoration work');
  await fixture({ stremio_detail_error: true });
  await page.locator('.stremio-title').first().click();
  await page.getByText('Could not load these episodes.', { exact: true }).waitFor();
  await fixture({ stremio_detail_error: false, stremio_sources_error: true });
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await page.getByRole('button', { name: 'Episode 2: At the park', exact: true }).click();
  await page.getByText('Could not load your sources.', { exact: true }).waitFor();
  await fixture({ stremio_sources_error: false, stremio_sources_empty: true });
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await page.getByText('No Torrentio Real-Debrid sources were found. Try again, or check Torrentio’s Real-Debrid connection in Stremio.', { exact: true }).waitFor();
  await fixture({ stremio_sources_empty: false, stremio_provider_failed: true });
  await page.getByRole('button', { name: 'Load sources again', exact: true }).click();
  await page.getByText('Some add-ons didn’t respond.', { exact: false }).waitFor();
  await filter.fill('no matches');
  await page.getByText('No sources match that filter.', { exact: true }).waitFor();
  checks.push('Metadata and source failures retry; empty, partial-provider and unmatched-filter states remain usable');
  await page.getByRole('button', { name: '‹ Episodes', exact: true }).click();
  await page.getByRole('button', { name: '‹ Watch Now', exact: true }).click();
  await page.locator('.stremio-title').last().click();
  await page.getByRole('heading', { name: 'Choose a source', exact: true }).waitFor();
  await filter.waitFor();
  if (await seasons.count() !== 0) throw Error('Film unnecessarily showed an episode chooser');
  checks.push('Films go directly to sources');
  for (const width of [320, 393, 852]) {
    await page.setViewportSize({ width, height: 852 });
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw Error('Horizontal overflow at ' + width);
  }
  if (errors.length) throw Error(errors.join('\n'));
  checks.push('320px, 393px and landscape layouts have no horizontal overflow or JavaScript errors');
  return { checks, errors };
}
