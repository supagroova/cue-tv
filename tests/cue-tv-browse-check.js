async (page) => {
  const root = 'http://127.0.0.1:8756';
  const checks = []; const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.request.post(root + '/__fixture', { data: { active: 'android', clear_events: true } });
  await page.setViewportSize({ width: 393, height: 852 }); await page.goto(root);
  await page.getByRole('button', { name: 'Watch', exact: true }).click();
  const trending = page.getByRole('heading', { name: 'Trending TV Shows on Netflix', exact: true });
  await trending.waitFor();
  await page.getByRole('heading', { name: 'Popular TV Shows on Netflix', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'New TV Shows on Apple TV+', exact: true }).waitFor();
  const distinct = await page.locator('.stremio-shelf').evaluateAll((rows) => rows.filter((row) => row.textContent.includes('on Netflix')).map((row) => [...row.querySelectorAll('b')].map((e) => e.textContent)));
  if (distinct.length !== 2 || JSON.stringify(distinct[0]) === JSON.stringify(distinct[1])) throw new Error('Different catalogue rankings were merged');
  checks.push('Phone shows distinct Trending, Popular and New service shelves');
  await page.waitForTimeout(250);
  await trending.scrollIntoViewIfNeeded(); await page.waitForTimeout(250);
  await page.screenshot({ path: 'output/apple-tv/cue-tv-phone-service-shelves.png' });
  await page.setViewportSize({ width: 1920, height: 1080 }); await page.goto(root + '/tv/watch.html');
  await page.getByRole('heading', { name: 'Trending TV Shows on Netflix', exact: true }).waitFor();
  await page.locator('.card').first().click();
  await page.getByRole('button', { name: 'Episodes & Sources', exact: true }).click();
  await page.getByRole('button', { name: 'Season 1', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Season 2', exact: true }).click();
  const episode = page.getByRole('button', { name: '1. Season two opener', exact: true });
  await episode.waitFor();
  if (!await page.getByRole('button', { name: '2. Not released yet Not released yet' }).isDisabled()) throw new Error('Future episode enabled');
  await episode.click(); await page.locator('.choices-list button').first().waitFor();
  const before = (await (await page.request.get(root + '/__fixture')).json()).events;
  if (before.some((event) => event.path === '/api/stremio/play')) throw new Error('Browsing started playback');
  await page.keyboard.press('Enter');
  await page.waitForFunction(async () => (await (await fetch('/__fixture')).json()).events.some((e) => e.path === '/api/stremio/play'));
  const events = (await (await page.request.get(root + '/__fixture')).json()).events;
  const play = events.filter((e) => e.path === '/api/stremio/play').at(-1);
  if (play.choice.quality !== '4K HDR' || !play.choice.video.endsWith(':2:1')) throw new Error('Exact episode and source changed');
  await page.waitForTimeout(250);
  await page.screenshot({ path: 'output/apple-tv/cue-tv-android-sources.png' });
  await page.keyboard.press('Escape');
  await episode.waitFor();
  await page.waitForTimeout(250);
  await page.screenshot({ path: 'output/apple-tv/cue-tv-android-episodes.png' });
  checks.push('Android TV browses seasons, episodes and RD sources, dispatches one exact selection, and Back retains season');
  if (errors.length) throw new Error(JSON.stringify(errors));
  return { checks, pageErrors: errors };
}
