async (page) => {
  const checks = [];
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const fixture = (data) => page.request.post('http://127.0.0.1:8756/__fixture', { data });
  await fixture({ active: 'android', clear_events: true });
  await page.setViewportSize({ width: 393, height: 852 });
  await page.goto('http://127.0.0.1:8756/');
  await page.getByRole('button', { name: 'Watch', exact: true }).click();
  await page.waitForFunction(() => { const el = document.querySelector('.pager'); return !document.querySelector('.watch-page').inert && (!el || el.scrollLeft > el.clientWidth * .99); });
  const stremio = page.getByRole('searchbox', { name: 'Search films and TV shows' });
  await stremio.fill('Bluey');
  await page.locator('.stremio-title').first().waitFor();
  const providers = page.getByRole('group', { name: 'Search platform' });
  await providers.getByRole('button', { name: 'YouTube', exact: true }).click();
  const search = page.getByRole('searchbox', { name: 'Search YouTube', exact: true });
  await search.fill('Melbourne');
  await page.getByRole('button', { name: 'Watch Melbourne video', exact: true }).waitFor();
  await page.screenshot({ path: 'output/apple-tv/phone-youtube-search.png' });
  checks.push('YouTube shows video artwork, titles, channel and duration');
  await providers.getByRole('button', { name: 'Stremio', exact: true }).click();
  if (await stremio.inputValue() !== 'Bluey') throw new Error('YouTube search overwrote Stremio');
  await providers.getByRole('button', { name: 'YouTube', exact: true }).click();
  if (await search.inputValue() !== 'Melbourne') throw new Error('Switching provider lost YouTube search');
  checks.push('Both providers keep their search and results');
  await search.fill('slow');
  await page.getByText('Searching YouTube…', { exact: true }).waitFor();
  await page.waitForResponse((response) => response.url().includes('/api/youtube/search?q=slow'));
  // An older response that resolves later must not overwrite the newest query.
  await search.fill('slow');
  await search.fill('slow ');
  await page.waitForRequest((request) => request.url().includes('/api/youtube/search?q=slow'));
  await search.fill('latest');
  await page.getByRole('button', { name: 'Watch latest video', exact: true }).waitFor();
  await page.waitForResponse((response) => response.url().includes('/api/youtube/search?q=slow'));
  if (await page.getByRole('button', { name: 'Watch slow video', exact: true }).count()) throw new Error('Older search replaced the latest query');
  checks.push('Latest search wins when responses arrive out of order');
  await search.fill('empty');
  await page.getByText('No videos found for “empty”.', { exact: true }).waitFor();
  await search.fill('error');
  await page.getByText('Couldn’t search YouTube right now.', { exact: true }).waitFor();
  const retried = page.waitForRequest((request) => request.url().includes('/api/youtube/search?q=error'));
  await page.getByRole('button', { name: 'Try again', exact: true }).click();
  await retried;
  await page.getByText('Couldn’t search YouTube right now.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Clear YouTube search' }).click();
  await page.getByText('What would you like to watch?', { exact: true }).waitFor();
  checks.push('Loading, empty, failed, retry and clear states work');
  await search.fill('Melbourne');
  const video = page.getByRole('button', { name: 'Watch Melbourne video', exact: true });
  await video.click();
  await page.getByRole('button', { name: 'Home', exact: true }).waitFor({ state: 'visible' });
  await fixture({ active: 'apple' });
  await page.waitForFunction(() => document.querySelector('select[aria-label="TV platform"]').value === 'apple');
  await page.getByRole('button', { name: 'Watch', exact: true }).click();
  await page.waitForFunction(() => { const el = document.querySelector('.pager'); return !document.querySelector('.watch-page').inert && (!el || el.scrollLeft > el.clientWidth * .99); });
  if (await search.inputValue() !== 'Melbourne') throw new Error('Opening a video lost the query');
  await video.click();
  await page.getByRole('button', { name: 'Home', exact: true }).waitFor({ state: 'visible' });
  const events = (await (await page.request.get('http://127.0.0.1:8756/__fixture')).json()).events;
  const opened = events.filter((event) => event.path === '/api/youtube/open');
  if (opened.length !== 2 || opened[0].platform !== 'android' || opened[1].platform !== 'apple' || opened.some((event) => event.body.id !== 'abcdefghijk')) throw new Error('YouTube did not dispatch on each active platform');
  checks.push('Tapping a video dispatches its ID on Android and Apple, then shows Remote');
  await page.getByRole('button', { name: 'Watch', exact: true }).click();
  await page.waitForFunction(() => { const el = document.querySelector('.pager'); return !document.querySelector('.watch-page').inert && (!el || el.scrollLeft > el.clientWidth * .99); });
  for (const width of [320, 393, 430, 900]) {
    await page.setViewportSize({ width, height: 852 });
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error(`Page overflow at ${width}px`);
  }
  if (errors.length) throw new Error(JSON.stringify(errors));
  checks.push('320px to 900px layouts have no page overflow or JavaScript exception');
  return { checks, opened, errors };
}
