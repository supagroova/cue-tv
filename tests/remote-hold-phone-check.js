async (page) => {
  const base = 'http://127.0.0.1:5400';
  const checks = [];
  const fixture = (value) => page.request.post(base + '/__fixture', { data: value });
  const keys = async () => (await (await page.request.get(base + '/__fixture')).json()).events.filter((e) => e.path === '/api/key').map((e) => e.body);
  const clear = () => fixture({ clear_events: true });
  const expectKeys = async (expected) => {
    await page.waitForTimeout(150);
    const actual = await keys();
    if (JSON.stringify(actual) !== JSON.stringify(expected)) throw new Error(JSON.stringify({ expected, actual }));
  };
  await fixture({ active: 'apple', clear_events: true });
  await page.setViewportSize({ width: 393, height: 852 });
  await page.goto(base);
  const pad = page.locator('.pad'); await pad.waitFor();
  await page.getByRole('button', { name: 'TV button. Hold for Control Centre', exact: true }).waitFor();
  const box = await pad.boundingBox();
  const x = box.x + box.width / 2; const y = box.y + box.height / 2;
  await page.mouse.click(x, y); await expectKeys([{ key: 'ok' }]);
  checks.push('Centre tap sends one Select');
  await clear();
  await page.mouse.move(x, y); await page.mouse.down(); await page.waitForTimeout(850); await page.mouse.up();
  await expectKeys([{ key: 'ok', hold: true }]);
  const selection = await pad.evaluate((el) => ({ css: getComputedStyle(el).webkitUserSelect || getComputedStyle(el).userSelect, selected: window.getSelection().toString() }));
  if (selection.css !== 'none' || selection.selected) throw new Error('Remote pad allows text selection');
  checks.push('Centre hold sends only held Select and selects no text');
  await clear();
  await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 65, y); await page.mouse.up();
  await expectKeys([{ key: 'right' }]); checks.push('Swipe cancels Select hold');
  await clear();
  await page.mouse.move(x, y); await page.mouse.down();
  await pad.dispatchEvent('pointercancel', { pointerId: 1, isPrimary: true });
  await page.waitForTimeout(700); await page.mouse.up();
  await expectKeys([]); checks.push('Cancelled gesture sends no key');
  const tv = page.getByRole('button', { name: 'TV button. Hold for Control Centre', exact: true });
  await tv.click(); await expectKeys([{ key: 'apple_tv' }]); checks.push('TV tap is separate from Home');
  await clear();
  const button = await tv.boundingBox(); await page.mouse.move(button.x + button.width / 2, button.y + button.height / 2);
  await page.mouse.down(); await page.waitForTimeout(850); await page.mouse.up();
  await expectKeys([{ key: 'apple_tv', hold: true }]); checks.push('TV hold sends one held TV button');
  await clear();
  await page.getByRole('button', { name: 'Home', exact: true }).click(); await expectKeys([{ key: 'home' }]);
  checks.push('Cue TV Home shortcut preserved');
  await page.screenshot({ path: 'output/apple-tv/cue-tv-held-controls.png' });
  await fixture({ active: 'android', clear_events: true });
  await page.waitForFunction(() => !document.querySelector('.apple-controls'));
  if (await tv.count()) throw new Error('Apple TV control shown on Android');
  await page.mouse.click(x, y); await expectKeys([{ key: 'ok' }]);
  checks.push('Android keeps existing controls');
  return { checks, selection };
}
